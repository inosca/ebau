def register_module(module):
    # We need to pass the locals of this file to the register method to make
    # sure they are injected on the conftest locals instead of the default
    # locals which would be the locals of this function
    conftest_locals = Box(sys._getframe(1).f_locals)

    for _, obj in inspect.getmembers(module):
        if isinstance(obj, FactoryMetaClass) and not obj._meta.abstract:
            _name = None

            # Our external factories have a property `_model_name_prefix` which
            # will cause the name of the model fixture to be prefixed
            # accordingly. This is needed in order to avoid naming collisions in
            # the model fixtures generated by pytest-factoryboy. E.g. the model
            # fixture for the caluma form model will be named `caluma_form`
            # instead of `form` which would result in a collision with the camac
            # form.
            if prefix := getattr(obj, "_model_name_prefix", None):
                _name = f"{prefix}_{get_model_name(obj)}"

            register(obj, _name=_name, _caller_locals=conftest_locals)


